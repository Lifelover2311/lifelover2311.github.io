function parseAxes(s){
  const v={}; if(!s||s==="—") return v;
  for(const part of s.split(/,\s*(?=[А-ЯЁ])/).map(x=>x.trim()).filter(Boolean)){
    const m=part.match(/^(\S+)(?:\s*×\s*([\d,\.]+))?$/); if(!m) throw new Error("bad "+part);
    const p=POLE[m[1]]; if(!p) throw new Error("pole "+m[1]);
    const w=m[2]?parseFloat(m[2].replace(",",".")):1;
    v[p[0]]=(v[p[0]]||0)+p[1]*w;
  }
  return v;
}
