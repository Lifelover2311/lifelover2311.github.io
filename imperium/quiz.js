function pearson(a,b){
  var n=a.length,ma=0,mb=0,i;for(i=0;i<n;i++){ma+=a[i];mb+=b[i];}ma/=n;mb/=n;
  var num=0,da=0,db=0;for(i=0;i<n;i++){var x=a[i]-ma,y=b[i]-mb;num+=x*y;da+=x*x;db+=y*y;}
  return (da&&db)?num/Math.sqrt(da*db):0;
}
